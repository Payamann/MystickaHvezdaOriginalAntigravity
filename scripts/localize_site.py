"""CZ-source translation builds. Network is opt-in; render defaults to noindex previews."""
from __future__ import annotations

import argparse
import hashlib
import html as html_module
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET

from localization.html_document import extract_page, render_page, segment_hash, validate_translation

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = Path("data/localization/manifest.json")
GENERATED = "<!-- Generated by localize_site.py; do not edit translated HTML directly. -->\n"


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True).encode()).hexdigest()


def contained(root, relative):
    path = (root / relative).resolve()
    if path == root.resolve() or not path.is_relative_to(root.resolve()):
        raise ValueError("Path leaves the selected project root")
    return path


def read_json(path, default=None):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def atomic_write(path, content):
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=path.parent, delete=False) as handle:
        handle.write(content)
        temporary = Path(handle.name)
    try:
        for attempt in range(5):
            try:
                os.replace(temporary, path)
                break
            except PermissionError:
                if attempt == 4:
                    raise
                time.sleep(0.05 * (attempt + 1))
    finally:
        temporary.unlink(missing_ok=True)


def write_json(path, value):
    atomic_write(path, json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def load_manifest(root):
    manifest = read_json(contained(root, MANIFEST))
    if not manifest or manifest.get("version") != 1 or manifest.get("sourceLanguage") != "cs":
        raise ValueError("Unsupported localization manifest")
    if manifest.get("origin") != "https://www.mystickahvezda.cz":
        raise ValueError("Unexpected site origin")
    ids, targets = set(), set()
    for page in manifest["pages"]:
        if page["id"] in ids:
            raise ValueError("Duplicate page ID")
        ids.add(page["id"])
        source = contained(root, page["source"])
        if not source.is_file() or source.suffix != ".html" or page["source"].startswith(("sk/", "pl/", "en/")):
            raise ValueError("Every source must be a real Czech HTML page")
        for locale, target in page["targets"].items():
            if locale not in manifest["locales"] or not target.startswith(locale + "/") or not target.endswith(".html"):
                raise ValueError("Invalid localized target")
            contained(root, target)
            if target in targets:
                raise ValueError("Duplicate localized target")
            targets.add(target)
    return manifest


def selected(manifest, page_id=None, locale=None):
    if page_id and page_id not in {p["id"] for p in manifest["pages"]}:
        raise ValueError("Unknown page ID")
    if locale and locale not in manifest["locales"]:
        raise ValueError("Unknown target language")
    return [(p, language) for p in manifest["pages"] if not page_id or p["id"] == page_id
            for language in p["targets"] if not locale or language == locale]


def cache_key(manifest, segment):
    return digest([manifest["policyVersion"], segment_hash(segment)])


def page_data(root, page):
    html = contained(root, page["source"]).read_text(encoding="utf-8")
    if re.search(r'<html\b[^>]*\blang=["\'](?!cs["\'])', html, re.I):
        raise ValueError("Source HTML is not Czech")
    segments = extract_page(html)
    if not segments:
        raise ValueError("Source has no translatable content")
    return html, segments, digest([(s["id"], segment_hash(s)) for s in segments])


def read_cache(root, locale):
    cache = read_json(contained(root, f"data/localization/cache/{locale}.json"), {"version": 1, "entries": {}})
    if cache.get("version") != 1 or not isinstance(cache.get("entries"), dict):
        raise ValueError("Invalid translation cache")
    return cache


def translations_for(manifest, segments, cache):
    translations, missing = {}, []
    for segment in segments:
        entry = cache["entries"].get(cache_key(manifest, segment))
        if not entry or entry.get("source") != segment["text"] or entry.get("sourceHash") != segment_hash(segment):
            missing.append(segment)
            continue
        validate_translation(segment["text"], entry["translation"])
        translations[segment["id"]] = entry["translation"]
    return translations, missing


def make_plan(root, manifest, selection):
    rows = []
    for page, locale in selection:
        _, segments, source_hash = page_data(root, page)
        _, missing = translations_for(manifest, segments, read_cache(root, locale))
        rows.append({"page": page["id"], "locale": locale, "sourceHash": source_hash,
                     "segments": len(segments), "missing": len(missing),
                     "charactersToTranslate": sum(len(s["text"]) for s in missing),
                     "target": page["targets"][locale]})
    return rows


def import_translations(root, manifest, selection, filename):
    if len(selection) != 1:
        raise ValueError("Import requires exactly one --page and --locale")
    page, locale = selection[0]
    _, segments, source_hash = page_data(root, page)
    supplied = read_json(Path(filename))
    if not supplied or supplied.get("sourceHash") != source_hash:
        raise ValueError("Import source is stale")
    values = supplied.get("translations", {})
    if set(values) != {s["id"] for s in segments}:
        raise ValueError("Import must cover the exact current segment IDs")
    # Validate all values before writing any of them.
    repeated = {}
    for segment in segments:
        target = values[segment["id"]]
        validate_translation(segment["text"], target)
        if segment["text"] in repeated and repeated[segment["text"]] != target:
            raise ValueError("Repeated source text has inconsistent translations")
        repeated[segment["text"]] = target
    cache = read_cache(root, locale)
    for segment in segments:
        cache["entries"][cache_key(manifest, segment)] = {
            "source": segment["text"], "sourceHash": segment_hash(segment),
            "translation": values[segment["id"]], "origin": "import"
        }
    write_json(contained(root, f"data/localization/cache/{locale}.json"), cache)


def batches_for(root, manifest, selection, size=1800):
    batches = []
    for page, locale in selection:
        _, segments, _ = page_data(root, page)
        _, missing = translations_for(manifest, segments, read_cache(root, locale))
        # Translate identical visible/FAQ strings once and copy the same value
        # to their distinct context hashes, preserving exact FAQ parity.
        grouped = {}
        for segment in missing:
            grouped.setdefault(segment["text"], []).append(segment)
        batch, length = [], 0
        for aliases in grouped.values():
            segment = aliases[0]
            amount = len(segment["text"])
            if amount > size:
                raise ValueError("A segment exceeds the batch limit; split the source paragraph first")
            if batch and (length + amount > size or len(batch) >= 20):
                batches.append((page, locale, batch))
                batch, length = [], 0
            batch.append(segment)
            length += amount
        if batch:
            batches.append((page, locale, batch))
    return batches


def translate_missing(root, manifest, selection, max_requests, max_characters):
    batches = batches_for(root, manifest, selection)
    characters = sum(len(s["text"]) for _, _, batch in batches for s in batch)
    if not batches:
        return {"requests": 0, "sourceCharacters": 0, "published": False}
    if max_requests < 1 or max_characters < 1 or len(batches) > max_requests or characters > max_characters:
        raise ValueError(f"Preflight budget exceeded: {len(batches)} requests / {characters} source characters; no calls made")
    node = shutil.which("node")
    if not node:
        raise ValueError("Node.js is required for the existing AI service")
    for page, locale, batch in batches:
        request = {"locale": locale, "segments": batch}
        result = subprocess.run([node, str(root / "scripts/localization/translate-batch.mjs")],
                                input=json.dumps(request, ensure_ascii=False), text=True, encoding="utf-8",
                                capture_output=True, timeout=90, cwd=root, check=False)
        if result.returncode:
            raise ValueError("Translation provider failed; valid earlier batches remain cached, nothing was published")
        try:
            values = json.loads(result.stdout)["translations"]
        except (ValueError, KeyError, TypeError) as exc:
            raise ValueError("Translation provider returned an invalid envelope") from exc
        if not isinstance(values, dict) or set(values) != {s["id"] for s in batch}:
            raise ValueError("Translation provider changed the segment set")
        for segment in batch:
            validate_translation(segment["text"], values[segment["id"]])
        cache = read_cache(root, locale)
        _, all_segments, _ = page_data(root, page)
        by_source = {segment["text"]: values[segment["id"]] for segment in batch}
        for segment in all_segments:
            if segment["text"] in by_source:
                cache["entries"][cache_key(manifest, segment)] = {
                    "source": segment["text"], "sourceHash": segment_hash(segment),
                    "translation": by_source[segment["text"]], "origin": "machine"
                }
        write_json(contained(root, f"data/localization/cache/{locale}.json"), cache)
    return {"requests": len(batches), "sourceCharacters": characters, "published": False}


def render_selection(root, manifest, selection, publish=False, approve=False, check=False):
    reviews_path = contained(root, "data/localization/reviews.json")
    reviews = read_json(reviews_path, {"version": 1, "pages": {}})
    if publish:
        for page, _ in selection:
            if {language for candidate, language in selection if candidate["id"] == page["id"]} != set(page["targets"]):
                raise ValueError("Publish requires all configured locales of a page together")
    # Compile the whole selection before any output write.
    compiled = []
    for page, locale in selection:
        html, segments, source_hash = page_data(root, page)
        translations, missing = translations_for(manifest, segments, read_cache(root, locale))
        if missing:
            raise ValueError(f"{page['id']}/{locale}: {len(missing)} missing or stale translations")
        translation_hash = digest(translations)
        review_key = f"{page['id']}/{locale}"
        approval = {"sourceHash": source_hash, "translationHash": translation_hash}
        if publish and page.get("reviewRequired", True) and reviews["pages"].get(review_key) != approval:
            raise ValueError(f"{review_key}: review does not match the current source and translation")
        source_url = manifest["origin"] + "/" + page["source"]
        target_url = manifest["origin"] + "/" + page["targets"][locale]
        alternates = {"cs": source_url}
        if publish:
            # Only variants compiled in this same release (or already generated)
            # are advertised. No links to unfinished language files.
            for language, target in page["targets"].items():
                candidate = contained(root, target)
                if (page, language) in selection or (candidate.exists() and candidate.read_text(encoding="utf-8").startswith(GENERATED)):
                    alternates[language] = manifest["origin"] + "/" + target
            alternates["x-default"] = source_url
        link_map = {manifest["origin"] + src: manifest["origin"] + values[locale]
                    for src, values in manifest.get("existingRoutes", {}).items() if locale in values}
        if manifest["origin"] + "/index.html" in link_map:
            link_map[manifest["origin"] + "/"] = link_map[manifest["origin"] + "/index.html"]
        for linked_page in manifest["pages"]:
            linked_target = linked_page["targets"].get(locale)
            if linked_target:
                linked_file = contained(root, linked_target)
                if (publish and (linked_page, locale) in selection) or (linked_file.exists() and linked_file.read_text(encoding="utf-8").startswith(GENERATED)):
                    link_map[manifest["origin"] + "/" + linked_page["source"]] = manifest["origin"] + "/" + linked_target
        output = GENERATED + render_page(html, translations, locale=locale, source_url=source_url,
                    target_url=target_url, alternates=alternates, preview=not publish, link_map=link_map)
        if publish:
            target = contained(root, page["targets"][locale])
            if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED):
                raise ValueError("Refusing to overwrite a hand-maintained localization")
        else:
            target = contained(root, f".tmp/localization-preview/{page['targets'][locale]}")
        if check and publish and (not target.exists() or target.read_text(encoding="utf-8") != output):
            raise ValueError(f"Generated page drift: {page['targets'][locale]}")
        compiled.append((page, locale, target, output, review_key, approval))
    if approve:
        for _, _, _, _, key, approval in compiled:
            reviews["pages"][key] = approval
        write_json(reviews_path, reviews)
    else:
        writes = {target: output for _, _, target, output, _, _ in compiled}
        if publish:
            routes = {language: {} for language in manifest["locales"]}
            for source, languages in manifest.get("existingRoutes", {}).items():
                for language, target in languages.items():
                    routes[language][source] = target
                    if source == "/index.html":
                        routes[language]["/"] = target
            seen_pages = set()
            for page, _, _, _, _, _ in compiled:
                if page["id"] in seen_pages:
                    continue
                seen_pages.add(page["id"])
                source = contained(root, page["source"])
                source_url = manifest["origin"] + "/" + page["source"]
                variants = {"cs": source_url, **{lang: manifest["origin"] + "/" + target for lang, target in page["targets"].items()}, "x-default": source_url}
                original = source.read_text(encoding="utf-8")
                cleaned = re.sub(r'<link\b(?=[^>]*\brel\s*=\s*["\']alternate["\'])(?=[^>]*\bhreflang\s*=)[^>]*>\s*', '', original, flags=re.I)
                tags = "\n".join(f'<link rel="alternate" hreflang="{lang}" href="{html_module.escape(url, quote=True)}">' for lang, url in variants.items())
                if not re.search(r'</head\s*>', cleaned, re.I):
                    raise ValueError("Source has no closing head")
                writes[source] = re.sub(r'</head\s*>', lambda _: tags + "\n</head>", cleaned, count=1, flags=re.I)
            # Preserve already published, generated pages outside this selection.
            for page in manifest["pages"]:
                for language, target in page["targets"].items():
                    path = contained(root, target)
                    if page["id"] in seen_pages or (path.exists() and path.read_text(encoding="utf-8").startswith(GENERATED)):
                        routes[language]["/" + page["source"]] = "/" + target
            writes[contained(root, "data/localization/routes.json")] = json.dumps(routes, ensure_ascii=False, indent=2) + "\n"
        if check:
            if publish:
                for target, output in writes.items():
                    if not target.exists() or target.read_text(encoding="utf-8") != output:
                        raise ValueError(f"Generated release drift: {target.relative_to(root)}")
        else:
            originals = {target: target.read_bytes() if target.exists() else None for target in writes}
            try:
                for target, output in writes.items():
                    atomic_write(target, output)
            except OSError:
                # These are individual, root-validated files owned by this build;
                # no directory deletion or broad rollback of user work occurs.
                for target, original in originals.items():
                    if original is None:
                        target.unlink(missing_ok=True)
                    else:
                        atomic_write(target, original.decode("utf-8"))
                raise
    return [{"page": p["id"], "locale": lang, "output": str(target.relative_to(root)), "preview": not publish}
            for p, lang, target, _, _, _ in compiled]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["plan", "extract", "import", "translate", "sync", "render", "approve", "check", "catalog"])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--page")
    parser.add_argument("--locale")
    parser.add_argument("--file")
    parser.add_argument("--publish", action="store_true")
    parser.add_argument("--max-requests", type=int, default=0)
    parser.add_argument("--max-characters", type=int, default=0)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    manifest = load_manifest(root)
    selection = selected(manifest, args.page, args.locale)
    if args.publish and args.command not in ("render", "check"):
        raise ValueError("--publish is only supported by render/check")
    if args.command == "plan":
        result = make_plan(root, manifest, selection)
    elif args.command == "extract":
        if len(selection) != 1:
            raise ValueError("Extract requires exactly one --page and --locale")
        page, locale = selection[0]
        _, segments, source_hash = page_data(root, page)
        result = {"page": page["id"], "locale": locale, "sourceHash": source_hash, "segments": segments}
    elif args.command == "import":
        if not args.file:
            raise ValueError("Import requires --file")
        import_translations(root, manifest, selection, args.file)
        result = make_plan(root, manifest, selection)
    elif args.command in ("translate", "sync"):
        result = translate_missing(root, manifest, selection, args.max_requests, args.max_characters)
        if args.command == "sync":
            result["previews"] = render_selection(root, manifest, selection)
    elif args.command == "catalog":
        enabled = {p["source"] for p in manifest["pages"]}
        urls = ET.parse(root / "sitemap.xml").getroot()
        result = [{"url": node.text, "enabled": node.text.removeprefix(manifest["origin"] + "/") in enabled}
                  for node in urls.findall("{*}url/{*}loc")
                  if not re.search(r"\.cz/(?:sk|pl|en)/", node.text)]
    else:
        result = render_selection(root, manifest, selection, publish=args.publish,
                                  approve=args.command == "approve", check=args.command == "check")
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    try:
        raise SystemExit(main())
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        print(f"Localization stopped: {error}", file=sys.stderr)
        raise SystemExit(1)
